#!/usr/bin/env node
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { parse as parseYaml, stringify as stringifyYaml } from "yaml";
import { format as formatWithPrettier } from "prettier";

const projectRoot = path.resolve(import.meta.dirname, "..");
const legacyRoot = path.resolve(
  process.env.LEGACY_HEXO_ROOT ?? "/Users/otis/Documents/hexoblog/blog",
);
const dryRun = process.argv.includes("--dry-run");
const clean = process.argv.includes("--clean");
const generatedHeader =
  "<!-- Generated by scripts/migrate-legacy-content.mjs. -->";
const reportPath = path.join(
  projectRoot,
  "docs/audit/content-migration-report.json",
);

const outputRoots = {
  blog: path.join(projectRoot, "src/content/blog"),
  drafts: path.join(projectRoot, "src/content/drafts"),
  pages: path.join(projectRoot, "src/content/pages"),
};

const manifest = JSON.parse(
  await readFile(
    path.join(projectRoot, "docs/audit/url-manifest-v1.json"),
    "utf8",
  ),
);
const routeBySource = new Map(
  manifest.articles.map((article) => [article.source, article]),
);
const assetRegister = JSON.parse(
  await readFile(
    path.join(projectRoot, "docs/audit/asset-recovery-register.json"),
    "utf8",
  ),
);
const unresolvedAssetPaths = new Set(
  assetRegister.assets
    .filter((asset) => asset.decision === "unresolved")
    .map((asset) => asset.legacyPath),
);

function splitFrontMatter(text, source) {
  const match = text.match(/^---\s*\n([\s\S]*?)\n---\s*(?:\n|$)/);
  if (!match) throw new Error(`${source}: missing YAML front matter`);
  return {
    data: parseYaml(match[1]) ?? {},
    body: text.slice(match[0].length),
  };
}

function list(value) {
  if (Array.isArray(value)) return value.map(String).filter(Boolean);
  if (typeof value === "string" && value.trim()) return [value.trim()];
  return [];
}

function optionalString(value) {
  if (value === undefined || value === null || value === "") return undefined;
  return String(value);
}

function legacyMetadata(data) {
  const metadata = {};
  for (const key of [
    "id",
    "thumbnail",
    "cover",
    "coverimg",
    "permalink",
    "comment",
  ]) {
    const value = data[key];
    if (value !== undefined && value !== null && value !== "") {
      metadata[key] = key === "id" ? String(value) : value;
    }
  }
  return Object.keys(metadata).length ? metadata : undefined;
}

function plainText(markdown) {
  return markdown
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/^\[[^\]]+\]:.*$/gm, " ")
    .replace(/^\[\^[^\]]+\]:.*$/gm, " ")
    .replace(/^[#>*+-]+\s*/gm, "")
    .replace(/[`*_~]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function deriveDescription(body) {
  const excerpt = body.split(/<!--\s*more\s*-->/i, 1)[0];
  const text = plainText(excerpt || body);
  if (!text) return undefined;
  return text.length > 160 ? `${text.slice(0, 157).trimEnd()}…` : text;
}

function normalizeBody(body, placeholderPaths) {
  let normalized = body
    .replace(/<!--\s*more\s*-->/gi, "")
    .replace(/\{%\s*github_emoji\s+([A-Za-z0-9_+-]+)\s*%\}/g, ":$1:")
    .replace(new RegExp(`[${String.fromCharCode(8)}\\uFEFF]`, "g"), "")
    .replace(/\]\(\.\.\/images\//g, "](/images/")
    .replace(/\]\(\.\/images\//g, "](/images/")
    .replace(/^(\[[^\]]+\]:\s*)\.\.\/images\//gm, "$1/images/")
    .replace(/^(\[[^\]]+\]:\s*)\.\/images\//gm, "$1/images/")
    .replace(/[ \t]+$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  for (const missingPath of placeholderPaths) {
    normalized = normalized.replaceAll(
      missingPath,
      `/images/missing-legacy-image.svg?missing=${encodeURIComponent(missingPath)}`,
    );
  }
  return normalized;
}

function migrationFrontMatter(data, source, kind) {
  if (kind === "blog") {
    const contract = routeBySource.get(source);
    if (!contract) throw new Error(`${source}: no approved URL contract entry`);
    return {
      title: String(data.title),
      description: deriveDescription(data.__body),
      date: String(data.date),
      legacyPath: contract.legacyPath,
      categories: list(data.categories),
      tags: list(data.tags),
      top: data.top === true,
      draft: false,
      topics: [],
      timeSensitive: false,
      legalDisclaimer: false,
      legacy: legacyMetadata(data),
    };
  }

  if (kind === "drafts") {
    return {
      title: String(data.title),
      ...(optionalString(data.date) ? { date: String(data.date) } : {}),
      categories: list(data.categories),
      tags: list(data.tags),
      draft: true,
      legacy: legacyMetadata(data),
    };
  }

  return {
    title: String(data.title),
    description: deriveDescription(data.__body),
    ...(optionalString(data.date) ? { updated: String(data.date) } : {}),
    draft: false,
  };
}

function outputName(source, kind) {
  if (kind === "pages") {
    const relative = source
      .replace(/^source\//, "")
      .replace(/\/index\.md$/, "");
    return `${relative.replaceAll("/", "--")}.md`;
  }
  return path.basename(source);
}

async function markdownFiles(directory) {
  return (await readdir(directory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"))
    .map((entry) => path.join(directory, entry.name))
    .sort();
}

const pageSources = [
  "source/about/index.md",
  "source/PGP/index.md",
  "source/timeline/index.md",
];
const jobs = [
  ...(await markdownFiles(path.join(legacyRoot, "source/_posts"))).map(
    (file) => ({ file, kind: "blog" }),
  ),
  ...(await markdownFiles(path.join(legacyRoot, "source/_drafts"))).map(
    (file) => ({ file, kind: "drafts" }),
  ),
  ...pageSources.map((source) => ({
    file: path.join(legacyRoot, source),
    kind: "pages",
  })),
];

if (clean && !dryRun) {
  for (const outputRoot of Object.values(outputRoots))
    await rm(outputRoot, { recursive: true, force: true });
}
for (const outputRoot of Object.values(outputRoots))
  if (!dryRun) await mkdir(outputRoot, { recursive: true });

const report = {
  schemaVersion: 1,
  legacyRoot,
  manifest: "docs/audit/url-manifest-v1.json",
  dryRun,
  generatedHeader,
  counts: { blog: 0, drafts: 0, pages: 0, assetsCopied: 0 },
  transformations: {
    moreMarkersRemoved: 0,
    githubEmojiTagsReplaced: 0,
    controlCharactersRemoved: 0,
    relativeImageReferencesNormalized: 0,
  },
  outputs: [],
};

for (const job of jobs) {
  const source = path.relative(legacyRoot, job.file).split(path.sep).join("/");
  const raw = await readFile(job.file, "utf8");
  const { data, body } = splitFrontMatter(raw, source);
  if (!data.title) throw new Error(`${source}: title is required`);
  if (job.kind === "blog" && !data.date)
    throw new Error(`${source}: published date is required`);

  report.transformations.moreMarkersRemoved += (
    body.match(/<!--\s*more\s*-->/gi) ?? []
  ).length;
  report.transformations.githubEmojiTagsReplaced += (
    body.match(/\{%\s*github_emoji\s+[^%]+%\}/g) ?? []
  ).length;
  report.transformations.controlCharactersRemoved += (
    body.match(new RegExp(`[${String.fromCharCode(8)}\\uFEFF]`, "g")) ?? []
  ).length;
  report.transformations.relativeImageReferencesNormalized += (
    body.match(/(?:\.\.\/|\.\/)images\//g) ?? []
  ).length;

  const normalizedBody = normalizeBody(body, unresolvedAssetPaths);
  const frontMatter = migrationFrontMatter(
    { ...data, __body: body },
    source,
    job.kind,
  );
  const rendered = await formatWithPrettier(
    `---\n${stringifyYaml(frontMatter, { lineWidth: 0 }).trim()}\n---\n\n${generatedHeader}\n\n${normalizedBody}\n`,
    { parser: "markdown", proseWrap: "preserve" },
  );
  const target = path.join(outputRoots[job.kind], outputName(source, job.kind));
  if (!dryRun) await writeFile(target, rendered, "utf8");
  report.counts[job.kind] += 1;
  report.outputs.push({
    source,
    target: path.relative(projectRoot, target).split(path.sep).join("/"),
    legacyPath: frontMatter.legacyPath,
  });
}

const legacyImages = path.join(legacyRoot, "source/images");
const publicImages = path.join(projectRoot, "public/images");
if (!dryRun) {
  await mkdir(publicImages, { recursive: true });
  await cp(legacyImages, publicImages, {
    recursive: true,
    force: false,
    errorOnExist: false,
    filter: (source) => path.basename(source) !== ".DS_Store",
  });
}
const countFiles = async (directory) => {
  let count = 0;
  for (const entry of await readdir(directory, { withFileTypes: true }))
    count += entry.isDirectory()
      ? await countFiles(path.join(directory, entry.name))
      : entry.name === ".DS_Store"
        ? 0
        : 1;
  return count;
};
report.counts.assetsCopied = await countFiles(legacyImages);

for (const name of ["google3756ddc34336b7b9.html", "keybase.txt", "CNAME"]) {
  if (!dryRun)
    await cp(
      path.join(legacyRoot, "source", name),
      path.join(projectRoot, "public", name),
    );
}

const reportText = `${JSON.stringify(report, null, 2)}\n`;
if (!dryRun) await writeFile(reportPath, reportText, "utf8");
console.log(reportText.trim());
